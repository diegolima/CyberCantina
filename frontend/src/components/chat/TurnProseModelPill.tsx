import React, { useEffect, useRef } from "react";
import { Activity, Feather, X } from "lucide-react";
import type { TurnNodeRecord } from "../../types";
import { formatTokenCount } from "./contextHealthHelpers";
import {
  computeProseSpeed,
  computeTurnTotalCostUsd,
  formatCostUsd,
  formatDurationMs,
  formatProseSpeed,
  formatShortModelLabel,
  getProseCallTelemetry,
  resolveProseProviderColor,
  resolveProseProviderLabel,
} from "./proseTelemetryHelpers";

export interface TurnProseModelPillProps {
  turn: TurnNodeRecord;
  isOpen: boolean;
  onToggle: () => void;
  onClose: () => void;
  onInspectFullTelemetry?: (turn: TurnNodeRecord) => void;
}

export const TurnProseModelPill: React.FC<TurnProseModelPillProps> = ({
  turn,
  isOpen,
  onToggle,
  onClose,
  onInspectFullTelemetry,
}) => {
  const anchorRef = useRef<HTMLDivElement | null>(null);
  const call = getProseCallTelemetry(turn.telemetry);

  useEffect(() => {
    if (!isOpen) return;
    const handlePointerDown = (e: MouseEvent) => {
      if (anchorRef.current && !anchorRef.current.contains(e.target as Node)) {
        onClose();
      }
    };
    const handleKeyDown = (e: KeyboardEvent) => {
      if (e.key === "Escape") {
        e.stopPropagation();
        onClose();
      }
    };
    document.addEventListener("mousedown", handlePointerDown);
    window.addEventListener("keydown", handleKeyDown);
    return () => {
      document.removeEventListener("mousedown", handlePointerDown);
      window.removeEventListener("keydown", handleKeyDown);
    };
  }, [isOpen, onClose]);

  if (!call || !call.model?.trim()) {
    return null;
  }

  const color = resolveProseProviderColor(call);
  const providerLabel = resolveProseProviderLabel(call);
  const shortModel = formatShortModelLabel(call.model);
  const durationLabel = formatDurationMs(call.duration_ms) ?? "—";
  const ttftLabel = formatDurationMs(call.ttft_ms);
  const speedText = formatProseSpeed(computeProseSpeed(call));
  const proseCostText = formatCostUsd(call.cost_usd);
  const turnTotalCost = computeTurnTotalCostUsd(turn.telemetry);
  const showTurnTotalCost = Boolean(
    turnTotalCost &&
      turnTotalCost.paidCallCount > 1 &&
      formatCostUsd(turnTotalCost.totalUsd) !== null,
  );
  const popoverId = `turn-model-popover-${turn.id}`;

  return (
    <div ref={anchorRef} className="turn-model-pill-anchor">
      <button
        type="button"
        className={`turn-model-pill turn-model-pill--${color}${isOpen ? " turn-model-pill--open" : ""}`}
        aria-expanded={isOpen}
        aria-controls={popoverId}
        aria-label={`Prose generated by ${call.model} via ${providerLabel}. Click for timing details.`}
        title={`Prose: ${call.model} (${providerLabel}) — click for generation metrics`}
        onClick={(e) => {
          e.stopPropagation();
          onToggle();
        }}
      >
        <Feather size={11} className="turn-model-pill-icon" aria-hidden="true" />
        <span className="turn-model-pill-label">{shortModel}</span>
      </button>

      {isOpen && (
        <div
          id={popoverId}
          role="dialog"
          aria-label="Prose generation details"
          className="ui-popover turn-model-popover"
          onClick={(e) => e.stopPropagation()}
        >
          <div className="turn-model-popover-header">
            <span className={`provider-pill provider-pill--${color} turn-model-popover-provider`}>
              <Feather size={11} aria-hidden="true" />
              <span>{providerLabel}</span>
            </span>
            <button
              type="button"
              className="btn btn-icon turn-model-popover-close"
              aria-label="Close prose generation details"
              onClick={onClose}
            >
              <X size={12} />
            </button>
          </div>

          <div className="turn-model-popover-model" title={call.model}>
            {call.model}
          </div>

          <div className="turn-model-popover-metrics">
            <div className="turn-model-popover-row">
              <span className="turn-model-popover-label">Generation time</span>
              <span className="turn-model-popover-value">{durationLabel}</span>
            </div>

            {ttftLabel && (
              <div className="turn-model-popover-row">
                <span className="turn-model-popover-label">First token (TTFT)</span>
                <span className="turn-model-popover-value">{ttftLabel}</span>
              </div>
            )}

            {speedText && (
              <div className="turn-model-popover-row">
                <span className="turn-model-popover-label">Speed</span>
                <span className="turn-model-popover-value">{speedText}</span>
              </div>
            )}

            <div className="turn-model-popover-row">
              <span className="turn-model-popover-label">Tokens</span>
              <span className="turn-model-popover-value">
                {formatTokenCount(call.prompt_tokens)} in · {formatTokenCount(call.completion_tokens)} out{" "}
                <span className="turn-model-popover-tag">
                  {call.usage_source === "exact" ? "Exact" : "Est."}
                </span>
              </span>
            </div>

            {call.finish_reason === "length" && (
              <div className="turn-model-popover-row">
                <span className="turn-model-popover-label">Stop reason</span>
                <span className="turn-model-popover-tag turn-model-popover-tag--danger">
                  Truncated (max tokens)
                </span>
              </div>
            )}

            {proseCostText && (
              <div className="turn-model-popover-row">
                <span className="turn-model-popover-label">
                  {showTurnTotalCost ? "Prose cost" : "Cost"}
                </span>
                <span className="turn-model-popover-value">{proseCostText}</span>
              </div>
            )}

            {showTurnTotalCost && turnTotalCost && (
              <div className="turn-model-popover-row">
                <span className="turn-model-popover-label">Turn total</span>
                <span className="turn-model-popover-value">
                  {formatCostUsd(turnTotalCost.totalUsd)}
                </span>
              </div>
            )}
          </div>

          {onInspectFullTelemetry && (
            <div className="turn-model-popover-footer">
              <button
                type="button"
                className="btn turn-model-popover-inspect-btn"
                onClick={() => {
                  onClose();
                  onInspectFullTelemetry(turn);
                }}
              >
                <Activity size={12} aria-hidden="true" />
                <span>Inspect all 4 phases</span>
              </button>
            </div>
          )}
        </div>
      )}
    </div>
  );
};
